"""Generate local, deterministic M2 data from M1. No credentials or network."""
from pathlib import Path
import base64
import gzip
import hashlib
import importlib.util
import json

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('eg_model', ROOT / 'core/demo-data/model.py')
model = importlib.util.module_from_spec(spec)
spec.loader.exec_module(model)

def build():
    data = model.make_dataset()
    model.validate(data)
    results = [model.analyze(data, c['id']) for c in data['changes']]
    evidence_ids = {e for r in results for c in r['consumers'] for e in c['evidence_ids']}
    relation_ids = {rid for r in results for c in r['consumers'] for p in c['paths'] for rid in p}
    bundle = {k: data[k] for k in ['synthetic','dataset_version','clock','teams','processes','sources','domains','assets']}
    bundle.update(results=results,
                  relations=[r for r in data['relations'] if r['id'] in relation_ids],
                  evidence=[e for e in data['evidence'] if e['id'] in evidence_ids],
                  coverage=[c for c in data['coverage'] if c['relation'] in relation_ids],
                  full_catalog_counts={'assets':len(data['assets']), 'relations':len(data['relations'])},
                  source_model_sha256=hashlib.sha256((ROOT/'core/demo-data/model.py').read_bytes()).hexdigest())
    # The complete inventory is included. Evidence and paths are limited to the prepared analyses.
    raw = json.dumps(bundle, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()
    packed = base64.b64encode(gzip.compress(raw, mtime=0)).decode()
    output = ROOT/'preview-m2'
    output.mkdir(exist_ok=True)
    (output/'data.js').write_text('// Generated by core/demo-ui/build_preview.py; gzip+base64, not encryption.\nwindow.EG_PACKED = '+json.dumps(packed)+';\n', encoding='utf-8')
    (output/'manifest.json').write_text(json.dumps({'dataset_version':data['dataset_version'], 'clock':data['clock'], 'assets':len(data['assets']), 'scenarios':len(results),'evidence_in_preview':len(evidence_ids), 'relations_in_preview':len(relation_ids),'bundle_sha256':hashlib.sha256(raw).hexdigest(),'source_model_sha256':bundle['source_model_sha256']},indent=2)+'\n')
    return bundle

if __name__ == '__main__':
    b = build()
    print(f"{len(b['assets'])} assets; {len(b['results'])} analyses; {len(b['evidence'])} evidence records")
